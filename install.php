// ------------------------------------------------------------------ requirement checks
function requirements(): array
{
    $req = [];
    $req[] = ['PHP 8.0 ขึ้นไป', version_compare(PHP_VERSION, '8.0.0', '>='), 'ปัจจุบัน ' . PHP_VERSION, true];
    foreach (['pdo' => 'PDO', 'pdo_mysql' => 'PDO MySQL (MariaDB driver)', 'mbstring' => 'mbstring', 'openssl' => 'OpenSSL',
                 'json' => 'JSON', 'session' => 'Session', 'ctype' => 'ctype'] as $ext => $label) {
        $req[] = ["ส่วนขยาย $label", extension_loaded($ext), extension_loaded($ext) ? 'ติดตั้งแล้ว' : "ต้องติดตั้ง php-$ext", true];
    }
    $disabled = array_map('trim', explode(',', (string)ini_get('disable_functions')));
    $procOk = function_exists('proc_open') && !in_array('proc_open', $disabled, true);
    $req[] = ['ฟังก์ชัน proc_open', $procOk, $procOk ? 'ใช้งานได้' : 'ถูกปิด — จะเรียกสคริปต์สร้างบัญชีและตรวจเซิร์ฟเวอร์ไม่ได้', false];
    $req[] = ['ส่วนขยาย posix', extension_loaded('posix'), extension_loaded('posix') ? 'ติดตั้งแล้ว' : 'แนะนำ (ใช้ตรวจกลุ่ม/ผู้ใช้ Linux)', false];
    $req[] = ['ฟังก์ชัน mail()', function_exists('mail'), 'ใช้ส่ง OTP ทางอีเมล', false];

    foreach (['config' => true, 'storage' => true, 'migrations' => false] as $dir => $required) {
        $path = BASE_PATH . "/$dir";
        if (!is_dir($path)) @mkdir($path, 0775, true);
        $ok = is_dir($path) && is_writable($path) && is_readable($path);
        $req[] = ["สิทธิ์อ่าน/เขียนโฟลเดอร์ $dir/", $ok,
            $ok ? 'อ่าน/เขียนได้' : "chown www-data $path && chmod 775 $path" . ($required ? '' : ' (จำเป็นเฉพาะการสร้าง migration จากหน้าเว็บ)'), $required];
    }
    if (is_file(CONFIG_FILE)) {
        $ok = is_writable(CONFIG_FILE);
        $req[] = ['สิทธิ์เขียนไฟล์ config/config.php', $ok, $ok ? 'เขียนทับได้' : 'ต้องให้สิทธิ์เขียนเพื่อติดตั้งซ้ำ', true];
    }
    return $req;
}

function requirements_ok(): bool
{
    foreach (requirements() as [, $ok, , $required]) if ($required && !$ok) return false;
    return true;
}

function write_config(array $db): void
{
    $cfg = ['db' => $db, 'app_key' => config('app_key') ?: bin2hex(random_bytes(16)), 'installed_at' => date('c')];
    $php = "<?php\n// Generated by install.php — " . date('Y-m-d H:i:s') . "\nreturn " . var_export($cfg, true) . ";\n";
    if (file_put_contents(CONFIG_FILE, $php, LOCK_EX) === false) throw new RuntimeException('เขียน config/config.php ไม่ได้');
    @chmod(CONFIG_FILE, 0640);
    if (function_exists('opcache_invalidate')) @opcache_invalidate(CONFIG_FILE, true);
}

function app_tables(PDO $pdo): array
{
    return $pdo->query('SHOW TABLES')->fetchAll(PDO::FETCH_COLUMN);
}

