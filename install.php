$installed = is_installed();
// A session that started while nothing was installed owns this installation run
if (!$installed) $S['auth'] = true;
if ($installed && empty($S['auth'])) {
    try {
        $u = current_user();
        if ($u && $u['role'] === 'admin') $S['auth'] = true;
    } catch (Throwable) {
        // DB may be broken — fall through to password gate
    }
}
if ($installed && empty($S['auth'])) {
    $step = 'gate';
    if ($_SERVER['REQUEST_METHOD'] === 'POST') {
        csrf_check();
        if (hash_equals((string)config('db.pass'), (string)($_POST['db_pass'] ?? '')) && post('db_user') === config('db.user')) {
            $S['auth'] = true;
            session_regenerate_id(true);
            redirect('install.php?step=requirements');
        }
        sleep(1);
        $error = 'ข้อมูลไม่ตรงกับ config/config.php';
    }
}

// ------------------------------------------------------------------ step handlers
if ($_SERVER['REQUEST_METHOD'] === 'POST' && $step !== 'gate') {
    csrf_check();
    try {
        if ($step === 'database') {
            if (!requirements_ok()) redirect('install.php?step=requirements');
            $db = ['host' => post('host', 'localhost'), 'port' => (int)post('port', '3306'), 'name' => post('name'),
                   'user' => post('user'), 'pass' => (string)($_POST['pass'] ?? '')];
            if ($db['pass'] === '' && !empty($S['db']['pass']) && post('keep_pass') === '1') $db['pass'] = $S['db']['pass'];
            if (!preg_match('/^[A-Za-z0-9_]{1,64}$/', $db['name'])) throw new RuntimeException('ชื่อฐานข้อมูลใช้ได้เฉพาะ A-Z a-z 0-9 _');

            $pdo = make_pdo($db, false);
            $ver = (string)$pdo->query('SELECT VERSION()')->fetchColumn();
            if (stripos($ver, 'mariadb') === false) throw new RuntimeException("ต้องใช้ MariaDB 10 ขึ้นไป (พบ $ver)");
            if ((int)$ver < 10) throw new RuntimeException("ต้องใช้ MariaDB 10 ขึ้นไป (พบ $ver)");
            if (post('create_db') === '1') {
                $pdo->exec("CREATE DATABASE IF NOT EXISTS `{$db['name']}` CHARACTER SET utf8mb4 COLLATE utf8mb4_unicode_ci");
            }
            $pdo = make_pdo($db);
            $S['db'] = $db;
            $S['db_version'] = $ver;
            $S['existing'] = app_tables($pdo);
            $S['mode'] = post('mode', 'upgrade') === 'fresh' ? 'fresh' : 'upgrade';

            if ($S['mode'] === 'fresh' && $S['existing']) {
                if (post('confirm_fresh') !== $db['name']) throw new RuntimeException('พิมพ์ชื่อฐานข้อมูลให้ถูกต้องเพื่อยืนยันการล้างข้อมูล');
                $pdo->exec('SET FOREIGN_KEY_CHECKS = 0');
                foreach ($S['existing'] as $t) $pdo->exec('DROP TABLE IF EXISTS `' . str_replace('`', '', $t) . '`');
                $pdo->exec('SET FOREIGN_KEY_CHECKS = 1');
            }
            write_config($db);
            $S['migrated'] = (new Migrator($pdo))->migrate();
            redirect('install.php?step=admin');
        }

        if ($step === 'admin') {
            if (empty($S['db'])) redirect('install.php?step=database');
            $pdo = make_pdo($S['db']);
            if (post('skip') === '1') {
                $n = (int)$pdo->query("SELECT COUNT(*) FROM users WHERE role='admin' AND status='active'")->fetchColumn();
                if ($n === 0) throw new RuntimeException('ยังไม่มีผู้ดูแลระบบ ต้องสร้างอย่างน้อย 1 บัญชี');
            } else {
                $user = strtolower(post('username'));
                $pass = (string)($_POST['password'] ?? '');
                if (!preg_match('/^[a-z][a-z0-9._-]{2,31}$/', $user)) throw new RuntimeException('Username ผู้ดูแล: a-z 0-9 . _ - ขึ้นต้นด้วยตัวอักษร 3–32 ตัว');
                if (strlen($pass) < 10) throw new RuntimeException('รหัสผ่านต้องมีอย่างน้อย 10 ตัวอักษร');
                if ($pass !== ($_POST['password2'] ?? '')) throw new RuntimeException('รหัสผ่านทั้งสองช่องไม่ตรงกัน');
                $email = post('email');
                if ($email !== '' && !filter_var($email, FILTER_VALIDATE_EMAIL)) throw new RuntimeException('อีเมลไม่ถูกต้อง');

                $st = $pdo->prepare('SELECT id, role FROM users WHERE username = ?');
                $st->execute([$user]);
                $ex = $st->fetch();
                if ($ex && $ex['role'] !== 'admin') throw new RuntimeException('username นี้เป็นบัญชีนักศึกษาอยู่แล้ว');
                $hash = password_hash($pass, PASSWORD_DEFAULT);
                if ($ex) {
                    $pdo->prepare("UPDATE users SET password_hash=?, full_name=?, email=?, status='active' WHERE id=?")
                        ->execute([$hash, post('full_name') ?: 'ผู้ดูแลระบบ', $email ?: null, $ex['id']]);
                } else {
                    $pdo->prepare("INSERT INTO users (username, password_hash, role, full_name, email, status, quota_soft_mb, quota_hard_mb)
                                   VALUES (?,?,'admin',?,?,'active',0,0)")
                        ->execute([$user, $hash, post('full_name') ?: 'ผู้ดูแลระบบ', $email ?: null]);
                }
                $pdo->prepare("INSERT INTO audit_log (actor, action, target, ip) VALUES ('installer','admin.set',?,?)")
                    ->execute([$user, $_SERVER['REMOTE_ADDR'] ?? '']);
            }
            file_put_contents(LOCK_FILE, date('c') . "\n" . APP_VERSION . "\n");
            $S['done'] = true;
            redirect('install.php?step=done');
        }
    } catch (Throwable $ex) {
        $error = $ex->getMessage();
    }
}

